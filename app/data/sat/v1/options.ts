import type { SatOption, TastingSectionId } from '../../../domain/sat/types'

function defineOptions(
  sectionId: TastingSectionId,
  ids: string[],
): SatOption[] {
  return ids.map((id) => ({
    id,
    sectionId,
    labelKey: `sat.options.${id}`,
  }))
}

